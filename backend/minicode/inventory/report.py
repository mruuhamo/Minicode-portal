"""Render an InventoryReport as Markdown and CSV."""

from __future__ import annotations

import csv
from collections import Counter
from pathlib import Path

from minicode.inventory.analysis import ISSUES, InventoryReport
from minicode.taxonomy import Taxonomy, load_taxonomy


def _table(headers: list[str], rows: list[list[object]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(str(c).replace("|", "\\|") for c in row) + " |" for row in rows]
    return "\n".join(lines)


def _code(text: str) -> str:
    return f"`{text}`"


def to_markdown(report: InventoryReport, taxonomy: Taxonomy | None = None) -> str:
    taxonomy = taxonomy or load_taxonomy()
    mock = report.source == "mock"
    status = report.status_counts()
    transcripts = report.transcript_counts()
    issues = report.issue_counts()
    with_issues = sum(1 for i in report.items if i.issues)
    extra_copies = sum(c - 1 for c in report.exact_duplicates.values())
    sim = " (SIMULATED)" if mock else ""

    out: list[str] = [
        "# Recording inventory report",
        "",
        "> Generated by `python -m minicode.inventory` - do not edit by hand; re-run the script instead.",
        f"> Source: **{report.source}**."
        + (
            " Titles are the real list exported from the minicode channel, but transcript availability"
            " and expired/deleted status are **simulated** until Graph `Sites.Selected` access is granted."
            if mock
            else ""
        ),
        "",
        "## Summary",
        "",
        _table(
            ["Metric", "Value"],
            [
                ["Recordings (rows)", report.total],
                ["Unique titles", report.unique_titles],
                ["Exact duplicate titles", f"{len(report.exact_duplicates)} titles, {extra_copies} extra copies"],
                ["Near-duplicate groups (same normalized title)", len(report.near_duplicates)],
                [f"With transcript{sim}", transcripts.get("yes", 0)],
                [f"Without transcript - needs Azure AI Speech{sim}", transcripts.get("no", 0)],
                [f"Available{sim}", status.get("available", 0)],
                [f"Expired{sim}", status.get("expired", 0)],
                [f"Deleted{sim}", status.get("deleted", 0)],
                ["Titles with at least one quality issue", f"{with_issues} ({with_issues * 100 // max(report.total, 1)} %)"],
            ],
        ),
        "",
        "## Scope warning: dates",
        "",
        "The export contains **no recording dates**. The project scope is *the last 1 year*, but the titles"
        " clearly span roughly **2018-2026** (e.g. 'Microsoft Build 2018', 'C# 8', 'VSTS', 'Fabcon Europe 2026')."
        " Dates found in titles are listed below; the real `createdDateTime` must come from Graph before the"
        " backfill scope can be fixed.",
        "",
        _table(["Year (from title)", "Recordings"], [[y, c] for y, c in sorted(report.year_hints().items())]),
        "",
        f"{report.total - sum(report.year_hints().values())} recordings have no date hint at all.",
        "",
        "## Title quality issues",
        "",
        _table(
            ["Issue", "Count", "Description"],
            [[_code(code), issues.get(code, 0), desc] for code, desc in ISSUES.items()],
        ),
        "",
    ]

    for code in ISSUES:
        affected = [i for i in report.items if code in i.issues]
        if not affected:
            continue
        out += [f"<details><summary><code>{code}</code> ({len(affected)})</summary>", ""]
        out += [f"- {_code(i.recording.title)} -> {i.normalized.display}" for i in affected]
        out += ["", "</details>", ""]

    out += ["## Duplicates", "", "### Exact duplicates", ""]
    out += [f"- {c}x {_code(t)}" for t, c in sorted(report.exact_duplicates.items())] or ["None."]
    out += ["", "### Near duplicates (same normalized title, different raw title)", ""]
    for group in report.near_duplicates:
        out.append("- " + " / ".join(_code(t) for t in group))
    if not report.near_duplicates:
        out.append("None.")

    series = report.series_counts()
    inferred = sum(1 for i in report.items if i.normalized.series_inferred)
    out += [
        "",
        "## Series (after normalization)",
        "",
        _table(["Series", "Recordings"], [[s, c] for s, c in series.most_common()]),
        "",
        f"{inferred} of these had no series prefix; their series was inferred (default `minicode`).",
        "",
        "## Tag coverage (keyword rules, see docs/taxonomy.md)",
        "",
    ]
    topic_counts = Counter(t for i in report.items for t in i.tags.topics)
    labels = {t.id: t.label for t in taxonomy.topic.tags}
    out.append(_table(["Topic", "Label", "Recordings"], [[_code(t), labels[t], c] for t, c in topic_counts.most_common()]))
    ct = Counter(i.tags.content_type for i in report.items)
    out += ["", _table(["Content type", "Recordings"], [[_code(k), v] for k, v in ct.most_common()]), ""]
    levels = Counter((i.tags.level, i.tags.level_source) for i in report.items)
    out += [
        _table(["Level", "Source", "Recordings"], [[lvl, src, c] for (lvl, src), c in sorted(levels.items())]),
        "",
        "Level is a weak heuristic for now (most titles default to 200); LLM enrichment in week 3 will assign it.",
        "",
    ]
    fallback = [i for i in report.items if i.tags.topics == (taxonomy.topic.fallback,)]
    out += [f"Recordings only tagged `{taxonomy.topic.fallback}` (need manual review): {len(fallback)}", ""]
    out += [f"- {_code(i.recording.title)}" for i in fallback]
    out += [
        "",
        "## Recommended clean-up actions",
        "",
        "1. Exclude non-recordings (`NON_RECORDING`) and collapse exact duplicates before backfill.",
        "2. Confirm near-duplicates with the channel owner (re-uploads vs. different sessions).",
        "3. Use the normalized title as display title; keep the original as `sourceTitle` metadata.",
        "4. Move presenter names and dates out of titles into metadata (Graph `createdBy` / `createdDateTime`).",
        "5. Re-run this report with `--source graph` once Sites.Selected access exists to get real dates,"
        " transcript availability and expired/deleted counts.",
        "",
    ]
    return "\n".join(out)


def to_csv(report: InventoryReport, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(
            ["id", "original_title", "normalized_title", "series", "part", "presenter", "date_hint",
             "topics", "content_type", "level", "level_source", "status", "has_transcript", "issues", "source"]
        )  # fmt: skip
        for i in report.items:
            n, t, r = i.normalized, i.tags, i.recording
            writer.writerow(
                [r.id, r.title, n.display, n.series, n.part or "", n.presenter or "", n.date_hint or "",
                 ";".join(t.topics), t.content_type, t.level, t.level_source, r.status.value,
                 "" if r.has_transcript is None else str(r.has_transcript).lower(), ";".join(i.issues), r.source]
            )  # fmt: skip
